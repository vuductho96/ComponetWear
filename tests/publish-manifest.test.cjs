const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { buildManifest } = require('../ComponentLife/publish-manifest.cjs');
test('hash cache avoids unchanged reads and detects same-size edits with restored mtime', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'manifest-cache-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const root = path.join(dir, 'public'), cacheDirectory = path.join(dir, 'private-cache');
  fs.mkdirSync(root);
  const file = path.join(root, 'data.json');
  fs.writeFileSync(file, '{"n":1}');
  fs.writeFileSync(path.join(root, 'model.bin'), Buffer.alloc(1024 * 1024, 7));
  const args = { root, files: ['data.json', 'model.bin'], cacheDirectory };
  const first = buildManifest(args), second = buildManifest(args);
  assert.equal(first.stats.hashed, 2);
  assert.deepEqual(second.stats, { hashed: 0, cached: 2, bytesRead: 0 });
  assert.equal(first.manifest.snapshotId, second.manifest.snapshotId);
  const before = fs.statSync(file);
  fs.writeFileSync(file, '{"n":2}');
  fs.utimesSync(file, before.atime, before.mtime);
  const changed = buildManifest(args);
  assert.equal(changed.stats.hashed, 1);
  assert.equal(changed.stats.cached, 1);
  assert.notEqual(changed.manifest.snapshotId, first.manifest.snapshotId);
  fs.writeFileSync(file, '{"n":!}');
  assert.throws(() => buildManifest(args), SyntaxError, 'Changed JSON must still validate');
  fs.writeFileSync(file, '{"n":2}');
  const cacheFile = path.join(cacheDirectory, fs.readdirSync(cacheDirectory)[0]);
  fs.writeFileSync(cacheFile, '{');
  assert.equal(buildManifest(args).stats.hashed, 2, 'Corrupt cache falls back to byte hashing');
  assert.throws(() => buildManifest({ ...args, files: [...args.files, 'missing.bin'] }), /ENOENT/);
  fs.unlinkSync(path.join(root, 'model.bin'));
  const removed = buildManifest({ ...args, files: ['data.json'] });
  assert.equal(removed.manifest.files.length, 1, 'Deleted assets leave the manifest and cache');
});
test('creating links to immutable generated previews reuses their verified hashes', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'preview-hash-cache-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const root = path.join(dir, 'public'), cacheDirectory = path.join(dir, 'cache');
  const relative = 'data/inspection/drawings/' + 'a'.repeat(64) + '-v1-p0001.webp';
  const file = path.join(root, relative);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, 'immutable preview');
  const args = { root, files: [relative], cacheDirectory };
  const before = buildManifest(args);
  fs.linkSync(file, path.join(dir, 'staging-link.webp'));
  const after = buildManifest(args);
  assert.equal(after.stats.hashed, 0);
  assert.equal(after.stats.cached, 1);
  assert.equal(after.manifest.snapshotId, before.manifest.snapshotId);
  fs.writeFileSync(file, 'changed preview');
  assert.equal(buildManifest(args).stats.hashed, 1, 'Actual changed bytes/mtime still invalidate the preview');
});
test('original download copies reuse hashes across staging hardlinks', t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'download-hash-cache-'));
  t.after(() => fs.rmSync(dir, {recursive:true,force:true}));
  const root = path.join(dir,'public'), cacheDirectory = path.join(dir,'cache');
  const files = ['pdf','xlsx','xlsm'].map(ext => 'data/inspection/downloads/' + 'a'.repeat(64) + '.' + ext);
  for (const file of files) { fs.mkdirSync(path.dirname(path.join(root,file)), {recursive:true}); fs.writeFileSync(path.join(root,file),'immutable original download'); }
  const args = {root,files,cacheDirectory};
  const before = buildManifest(args);
  for (const [i,file] of files.entries()) fs.linkSync(path.join(root,file),path.join(dir,'link-'+i));
  const after = buildManifest(args);
  assert.equal(after.stats.hashed,0);
  assert.equal(after.manifest.snapshotId,before.manifest.snapshotId);
});
